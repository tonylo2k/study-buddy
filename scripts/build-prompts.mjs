// Turns prompts/*.md into string constants (src/lib/server/prompts.generated.ts)
// so API routes never read the filesystem at runtime. Run: npm run prompts
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "prompts");
const out = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
  const text = readFileSync(join(dir, f), "utf8");
  const sys = text.indexOf("## System");
  const usr = text.indexOf("## User");
  if (sys < 0 || usr < 0) throw new Error(`${f}: missing ## System / ## User`);
  out[f.replace(/\.md$/, "")] = {
    system: text.slice(sys + "## System".length, usr).trim(),
    user: text.slice(usr + "## User".length).trim(),
  };
}
const body =
  "// GENERATED by scripts/build-prompts.mjs from prompts/*.md. Do not edit by hand.\n" +
  "export const PROMPTS = " + JSON.stringify(out, null, 2) + " as const;\n" +
  "export type PromptName = keyof typeof PROMPTS;\n";
writeFileSync(join(root, "src/lib/server/prompts.generated.ts"), body);
console.log("wrote", Object.keys(out).length, "prompts");
